export function translate(language, message, values = {}) {
  const template = language === 'ar' ? arabicMessages[message] ?? message : message;
  return template.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}

export const languageDirection = language => language === 'ar' ? 'rtl' : 'ltr';
export const localizeNumber = (language, value) => language === 'ar'
  ? String(value).replace(/\d/g, digit => '٠١٢٣٤٥٦٧٨٩'[digit]) : String(value);
export const normalizeDigits = text => text.replace(/[٠-٩۰-۹]/g, digit =>
  String('٠١٢٣٤٥٦٧٨٩'.includes(digit) ? '٠١٢٣٤٥٦٧٨٩'.indexOf(digit) : '۰۱۲۳۴۵۶۷۸۹'.indexOf(digit)));

export function ayahCount(language, count) {
  if (language !== 'ar') return `${count} ayahs`;
  if (count === 1) return 'آية واحدة';
  if (count === 2) return 'آيتان';
  return `${localizeNumber(language, count)} ${count % 100 >= 3 && count % 100 <= 10 ? 'آيات' : 'آية'}`;
}
